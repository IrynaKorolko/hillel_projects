def say_hi(name: str, age: int) -> str:
    """Функція приймає ім'я та вік як аргументи та повертає привітання

Аргументи:
    name (str): Ім'я користувача
    age (int): Вік користувача

Повертає:
    рядок типу str: Привітання юзера у форматі "Привіт,
    я {name} і мені {age} років"."""
    return f"Привіт, я {name} і мені {age} років"

print(say_hi("Ірина", 10))
